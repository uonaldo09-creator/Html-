const directoryProfile = (source: (typeof sources)[number], directoryOnly: boolean) => ({
  sourceName: "sourceName" in source ? source.sourceName : source.name,
  established: source.established,
  accreditation: source.accreditation,
  rankings: source.rankings,
  courses: source.courses,
  feeRange: source.feeRange,
  scholarships: source.scholarships,
  sourceNote,
  ...(directoryOnly ? { directoryOnly: true } : {}),
});

function toUniversity(source: (typeof sources)[number], id: number): University {
  const searchText = `${source.name} ${source.courses}`.toLowerCase();
  const stream = [
    ["Engineering", /engineer|b\.?tech|m\.?tech/],
    ["Management", /management|business|mba|bba/],
    ["Law", /law|llb/],
    ["Medical", /medicine|mbbs|nursing|pharmacy|ayurveda|health|physiotherapy/],
    ["Science", /science|phd|research/],
    ["Arts", /arts|humanities|journalism|design|education/],
  ].filter(([, pattern]) => (pattern as RegExp).test(searchText)).map(([label]) => label as string);

  return {
    id,
    name: source.name,
    location: source.location,
    state: "Uttarakhand",
    type: "Private",
    degreeLevel: [],
    fee: 0,
    rating: 0,
    students: "Not listed",
    courses: 0,
    image: `https://picsum.photos/seed/uttarakhand-university-${id}/800/500`,
    categories: ["Private University"],
    stream,
    degrees: [],
    majors: [],
    popularCourses: [source.courses],
    phone: "",
    competitiveExams: [],
    min10th: 0,
    min12th: 0,
    naacGrade: "Not listed",
    nirfRank: 0,
    aicteApproved: false,
    nbaAccredited: false,
    nmcRecognized: false,
    avgPlacementLPA: 0,
    website: source.website,
    reviews: [],
    directoryProfile: directoryProfile(source, true),
    campusMap: {
      acreage: 0,
      established: Number(source.established.match(/\b(?:19|20)\d{2}\b/)?.[0] ?? 0),
      hasHostels: false,
      totalBuildings: 0,
      zones: [],
    },
  };
}

export function getUttarakhandUniversityDirectory(existingUniversities: University[]): University[] {
  const existingByWebsite = new Map(
    existingUniversities
      .filter((university) => university.website)
      .map((university) => [university.website!.replace(/\/$/, "").toLowerCase(), university]),
  );
  const directoryEntries: University[] = [];

  sources.forEach((source, index) => {
    const websiteKey = source.website.replace(/\/$/, "").toLowerCase();
    const existing = existingByWebsite.get(websiteKey);
    if (existing) {
      if (!existing.directoryProfile) {
        existing.directoryProfile = directoryProfile(source, false);
      }
      return;
    }
    directoryEntries.push(toUniversity(source, 1001 + index));
  });

  return directoryEntries;
}


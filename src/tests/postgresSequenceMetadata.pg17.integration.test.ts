import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { Client } from "pg";
import { PostgresMigrationSource } from "../server/postgresMigrationSource";
import type { SourceTable } from "../server/convexMigration";

/**
 * Real PostgreSQL 17+ integration verification for sequence metadata SQL.
 *
 * Runs ONLY when explicitly enabled with a disposable, non-production admin/test
 * connection (never King):
 *   ALLOW_POSTGRES_17_INTEGRATION_TESTS=1
 *   POSTGRES_TEST_ADMIN_URL=<postgresql://...>  (value never printed)
 *
 * Creates and drops a uniquely named temporary database. Executes
 * PostgresMigrationSource's actual SEQUENCE_METADATA_SQL and readIdCounterFloor()
 * behavior — no simplified query copy.
 *
 * The test temporarily needs DDL/role management in its disposable DB only.
 * The migration reader role created inside the disposable DB is granted only the
 * minimum privileges under test (SELECT on specific tables/sequences as needed).
 */
const enabled = process.env.ALLOW_POSTGRES_17_INTEGRATION_TESTS === "1";
const adminUrl = process.env.POSTGRES_TEST_ADMIN_URL;
const shouldRun = enabled && typeof adminUrl === "string" && adminUrl.length > 0;

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function makeSource(client: Client): PostgresMigrationSource {
  return new PostgresMigrationSource(client as any);
}

describe.runIf(shouldRun)("PostgresMigrationSource sequence metadata on real PostgreSQL 17+", () => {
  let admin: Client;
  let dbName = "";
  let testUrl = "";
  let readerUrl = "";

  beforeAll(async () => {
    admin = new Client({ connectionString: adminUrl });
    await admin.connect();
    const version = await admin.query("SELECT current_setting('server_version_num')::int AS n");
    const major = Math.floor(Number(version.rows[0]?.n ?? 0) / 10000);
    if (major < 17) {
      throw new Error(`PostgreSQL 17+ required for integration verification; found server version major ${major}.`);
    }

    dbName = `uniinfo_seq_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
    await admin.query(`CREATE DATABASE ${quoteIdent(dbName)}`);

    const u = new URL(adminUrl!);
    u.pathname = `/${dbName}`;
    testUrl = u.toString();

    // Create a disposable low-privilege reader role in the cluster and set its password.
    await admin.query(`DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='uniinfo_seq_reader') THEN CREATE ROLE uniinfo_seq_reader LOGIN PASSWORD 'uniinfo_seq_reader_test'; ELSE ALTER ROLE uniinfo_seq_reader PASSWORD 'uniinfo_seq_reader_test'; END IF; END $$`);
    const ru = new URL(testUrl);
    ru.username = "uniinfo_seq_reader";
    ru.password = "uniinfo_seq_reader_test";
    readerUrl = ru.toString();

    const setup = new Client({ connectionString: testUrl });
    await setup.connect();
    try {
      await setup.query(`
        -- allowlisted migration tables used by PostgresMigrationSource
        CREATE TABLE users (id serial PRIMARY KEY, email text);
        CREATE TABLE reviews (id serial PRIMARY KEY, university_id integer);
        CREATE TABLE bookmarks (id serial PRIMARY KEY, user_email text, university_id integer);
        CREATE TABLE chat_history (id serial PRIMARY KEY, role text);
        CREATE TABLE audit_logs (id integer PRIMARY KEY); -- no sequence
        CREATE TABLE login_attempts (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
        CREATE TABLE sessions (token text PRIMARY KEY, email text);
        CREATE TABLE university_reviews_agg (university_id integer PRIMARY KEY);
        CREATE TABLE analytics_events (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
        CREATE TABLE student_profiles (id serial PRIMARY KEY);
        CREATE TABLE parent_profiles (id serial PRIMARY KEY);
        CREATE TABLE notifications (id serial PRIMARY KEY);
        CREATE TABLE universities (id serial PRIMARY KEY);

        -- populated ordinary serial
        INSERT INTO reviews (university_id) VALUES (1),(1),(1);
        DELETE FROM reviews WHERE id = 3;

        -- identity populated
        INSERT INTO login_attempts DEFAULT VALUES;
        INSERT INTO login_attempts DEFAULT VALUES;
        INSERT INTO analytics_events DEFAULT VALUES;
        SELECT setval(pg_get_serial_sequence('analytics_events','id'), 232, true);

        -- bookmarks scenario: row maximum 6, sequence high-water 232 => floor 233
        INSERT INTO bookmarks (id, user_email, university_id) VALUES (6, 'x@example.test', 1);
        SELECT setval(pg_get_serial_sequence('bookmarks','id'), 232, true);

        -- genuinely unused/fresh serial: users left empty and users_id_seq untouched after CREATE TABLE

        -- regression: SETVAL(sequence, 500, false) means next nextval() returns 500
        SELECT setval(pg_get_serial_sequence('universities','id'), 500, false);

        GRANT CONNECT ON DATABASE ${quoteIdent(dbName)} TO uniinfo_seq_reader;
        GRANT USAGE ON SCHEMA public TO uniinfo_seq_reader;
        GRANT SELECT ON TABLE users,reviews,bookmarks,chat_history,audit_logs,login_attempts,sessions,university_reviews_agg,analytics_events,student_profiles,parent_profiles,notifications,universities TO uniinfo_seq_reader;
        -- SELECT on sequences for inspection cases; omit audit_logs has no sequence, and revoke one to test missing permission.
        GRANT SELECT ON SEQUENCE users_id_seq,reviews_id_seq,bookmarks_id_seq,chat_history_id_seq,login_attempts_id_seq,analytics_events_id_seq,student_profiles_id_seq,parent_profiles_id_seq,notifications_id_seq,universities_id_seq TO uniinfo_seq_reader;
        -- intentionally do NOT grant SELECT on chat_history_id_seq? granted above; revoke below.
        REVOKE SELECT ON SEQUENCE chat_history_id_seq FROM uniinfo_seq_reader;
        -- no USAGE/UPDATE granted
      `);
    } finally {
      await setup.end();
    }
  }, 120_000);

  afterAll(async () => {
    if (admin) {
      try {
        if (dbName) {
          await admin.query(
            `SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1 AND pid <> pg_backend_pid()`,
            [dbName],
          );
          await admin.query(`DROP DATABASE IF EXISTS ${quoteIdent(dbName)}`);
        }
      } finally {
        await admin.query(`DROP ROLE IF EXISTS uniinfo_seq_reader`);
        await admin.end();
      }
    }
  }, 120_000);

  it("executes PostgresMigrationSource.SEQUENCE_METADATA_SQL against real PostgreSQL catalogs", async () => {
    const client = new Client({ connectionString: testUrl });
    await client.connect();
    try {
      await client.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY");
      const result = await client.query(PostgresMigrationSource.SEQUENCE_METADATA_SQL, [
        "public.bookmarks",
        "id",
      ]);
      expect(result.rows[0]).toMatchObject({
        sequence_schema: "public",
        sequence_name: "bookmarks_id_seq",
        seqincrement: "1",
        seqcache: "1",
        seqcycle: false,
        can_select: true,
      });
      expect(result.rows[0]).not.toHaveProperty("last_value");
      expect(result.rows[0]).not.toHaveProperty("is_called");
      await client.query("COMMIT");
    } finally {
      await client.end();
    }
  });

  it("reads runtime state only inside repeatable-read read-only transaction via readIdCounterFloor", async () => {
    const client = new Client({ connectionString: testUrl });
    await client.connect();
    const source = makeSource(client);
    try {
      await expect(source.readIdCounterFloor("bookmarks")).rejects.toThrow(/active read-only snapshot/);
      await source.beginReadOnlySnapshot();
      await expect(source.readIdCounterFloor("bookmarks")).resolves.toEqual({ maxLegacyId: 6, sequenceNextId: 233 });
      await expect(client.query("CREATE TEMP TABLE should_fail(x int)")).rejects.toBeTruthy();
      await source.close();
    } finally {
      await client.end();
    }
  });

  it("covers serial/identity populated, fresh/SETVAL(false) regression, missing privilege/no-sequence/token/agg cases", async () => {
    const client = new Client({ connectionString: testUrl });
    await client.connect();
    const source = makeSource(client);
    try {
      await source.beginReadOnlySnapshot();
      await expect(source.readIdCounterFloor("reviews")).resolves.toEqual({ maxLegacyId: 2, sequenceNextId: 4 });
      await expect(source.readIdCounterFloor("analyticsEvents")).resolves.toEqual({ maxLegacyId: 1, sequenceNextId: 233 });
      // genuinely fresh sequence: initial last_value used (is_called=false)
      await expect(source.readIdCounterFloor("users")).resolves.toEqual({ maxLegacyId: 0, sequenceNextId: 1 });
      // regression: SETVAL(500,false) => next safe boundary is last_value (500), not seqstart
      await expect(source.readIdCounterFloor("universities")).resolves.toEqual({ maxLegacyId: 0, sequenceNextId: 500 });
      await expect(source.readIdCounterFloor("auditLogs")).resolves.toEqual({ maxLegacyId: 0, sequenceNextId: null });
      await expect(source.readIdCounterFloor("sessions")).resolves.toEqual({ maxLegacyId: 0, sequenceNextId: null });
      await expect(source.readIdCounterFloor("universityReviewsAgg")).resolves.toEqual({ maxLegacyId: 0, sequenceNextId: null });
      await source.close();
    } finally {
      await client.end();
    }
  });

  it("fails closed when SELECT permission on sequence is missing (reader role)", async () => {
    const client = new Client({ connectionString: readerUrl });
    await client.connect();
    const source = makeSource(client);
    try {
      await source.beginReadOnlySnapshot();
      await expect(source.readIdCounterFloor("chatHistory")).rejects.toThrow(/Missing SELECT privilege|failing closed/i);
      await source.close();
    } finally {
      await client.end();
    }
  });

  it("succeeds with SELECT on sequence but without USAGE/UPDATE for reader role", async () => {
    const client = new Client({ connectionString: readerUrl });
    await client.connect();
    const source = makeSource(client);
    try {
      await source.beginReadOnlySnapshot();
      await expect(source.readIdCounterFloor("bookmarks")).resolves.toEqual({ maxLegacyId: 6, sequenceNextId: 233 });
      await source.close();
    } finally {
      await client.end();
    }
  });

  it("never calls nextval/currval/setval", async () => {
    const statements: string[] = [];
    const client = new Client({ connectionString: testUrl });
    const original = client.query.bind(client);
    (client as any).query = (text: any, values?: any) => {
      if (typeof text === "string") statements.push(text);
      return original(text, values);
    };
    await client.connect();
    const source = makeSource(client);
    try {
      await source.beginReadOnlySnapshot();
      await source.readIdCounterFloor("bookmarks");
      await source.close();
      expect(statements.some((s) => /\bnextval\b|\bcurrval\b|\bsetval\b/i.test(s))).toBe(false);
    } finally {
      await client.end();
    }
  });
});

describe.runIf(!shouldRun)("PostgresMigrationSource PG17 integration (infrastructure unavailable)", () => {
  it("skipped: requires ALLOW_POSTGRES_17_INTEGRATION_TESTS=1 and POSTGRES_TEST_ADMIN_URL for a disposable non-production PostgreSQL 17+ database", () => {
    expect(shouldRun).toBe(false);
  });
});
